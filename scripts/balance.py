"""Balance check: were treated and control exposures alike before the exposure?

Uses only things fixed before each random exposure. Computes no outcome.
Writes results/balance.md and results/balance.json.

    python scripts/balance.py
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src import estimate, events, topics  # noqa: E402

THRESHOLD = 0.05  # pre-registered: stop if the pooled baseline difference exceeds this


def covariates(study: events.Study) -> dict[str, np.ndarray]:
    """Each covariate as a (topics, events) matrix. Only the baseline share differs by topic."""
    ev, n_topics = study.events, len(study.targets)
    a, b = events.before_window(ev, events.BASELINE_N)
    day = pd.to_datetime(ev["date"].astype(str), format="%Y%m%d")
    reg = ev["user_id"].map(study.users.set_index("user_id")["register_days"]).to_numpy(dtype=float)
    same = {
        "Day of the experiment": (day - day.min()).dt.days.to_numpy(dtype=float),
        "Hour of the day": (ev["hourmin"] // 100).to_numpy(dtype=float),
        "Ordinary impressions before the exposure": (ev["lo"] - ev["s"]).to_numpy(dtype=float),
        "Days since registration": reg,
    }
    out = {"Baseline share of the topic (last 100 impressions)": events.share_matrix(study.feed, study.targets, a, b)}
    out.update({k: np.broadcast_to(v, (n_topics, len(v))) for k, v in same.items()})
    return out


def standardised(y: np.ndarray) -> np.ndarray:
    """Divide each topic's row by its standard deviation over all events."""
    sd = np.nanstd(y, axis=1, ddof=1, keepdims=True)
    return y / np.where(sd > 0, sd, np.nan)


def balance_rows(study: events.Study, weights: np.ndarray) -> tuple[list[dict], list[dict]]:
    codes, n_users = estimate.user_codes(study.events["user_id"].to_numpy())
    treated = events.treated_matrix(study.events["topic"].to_numpy(), study.targets)
    pooled, per_topic = [], []
    for name, y in covariates(study).items():
        raw = estimate.diff_in_means(y, treated, codes, n_users)
        smd = estimate.diff_in_means(standardised(y), treated, codes, n_users, weights)
        lo, hi = smd.interval(0.95)
        pooled.append({"covariate": name, "treated_mean": raw.pooled_treated_mean,
                       "control_mean": raw.pooled_control_mean, "smd": smd.pooled, "lo": lo, "hi": hi})
        if name.startswith("Baseline"):
            ci = smd.topic_intervals(0.95)
            for i, t in enumerate(study.targets):
                per_topic.append({"topic": t, "name": topics.ENGLISH.get(t, str(t)),
                                  "n_treated": int(raw.n_treated[i]), "n_control": int(raw.n_control[i]),
                                  "treated_mean": float(raw.treated_mean[i]), "control_mean": float(raw.control_mean[i]),
                                  "smd": float(smd.effect[i]), "lo": float(ci[i, 0]), "hi": float(ci[i, 1])})
    return pooled, per_topic


def to_markdown(pooled: list[dict], per_topic: list[dict], counts: dict) -> str:
    base = pooled[0]
    verdict = "passes" if abs(base["smd"]) <= THRESHOLD else "FAILS"
    lines = [
        "# Balance of treated and control exposures",
        "",
        "Generated by `scripts/balance.py`. For each target topic, an exposure is treated if",
        "its random video is in that topic and a control otherwise. Everything here was fixed",
        "before the exposure. Differences are in standard deviations, pooled over the 13 topics",
        "(weighted by treated exposures), with 95% intervals from a bootstrap over users.",
        "",
        f"Random exposures: {counts['events']:,} from {counts['users']:,} users. "
        f"{counts['no_before']:,} have no ordinary impression before them and so no baseline.",
        "",
        "| Before the exposure | Treated mean | Control mean | Difference (SD) | 95% interval |",
        "|---|---:|---:|---:|---|",
    ]
    for r in pooled:
        pct = r["covariate"].startswith("Baseline")
        fmt = (lambda v: f"{100 * v:.2f}%") if pct else (lambda v: f"{v:,.1f}")
        lines.append(f"| {r['covariate']} | {fmt(r['treated_mean'])} | {fmt(r['control_mean'])} | "
                     f"{r['smd']:+.3f} | {r['lo']:+.3f} to {r['hi']:+.3f} |")
    lines += [
        "",
        f"Pre-registered rule: stop if the pooled baseline difference is beyond ±{THRESHOLD} SD. "
        f"It is {base['smd']:+.3f}, so the check {verdict}.",
        "",
        "## Baseline share by topic",
        "",
        "| Topic | Treated | Control | Treated baseline | Control baseline | Difference (SD) | 95% interval |",
        "|---|---:|---:|---:|---:|---:|---|",
    ]
    for r in per_topic:
        lines.append(f"| {r['name']} | {r['n_treated']:,} | {r['n_control']:,} | {100 * r['treated_mean']:.2f}% | "
                     f"{100 * r['control_mean']:.2f}% | {r['smd']:+.3f} | {r['lo']:+.3f} to {r['hi']:+.3f} |")
    lines.append("")
    return "\n".join(lines)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--raw-dir", default="data/raw")
    p.add_argument("--processed-dir", default="data/processed")
    p.add_argument("--out-dir", default="results")
    args = p.parse_args(argv)

    study = events.load_study(args.raw_dir, args.processed_dir)
    codes, n_users = estimate.user_codes(study.events["user_id"].to_numpy())
    pooled, per_topic = balance_rows(study, estimate.bootstrap_weights(n_users))
    counts = {"events": int(len(study.events)), "users": int(n_users),
              "no_before": int((study.events["lo"] == study.events["s"]).sum())}
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "balance.json").write_text(json.dumps({"counts": counts, "pooled": pooled, "by_topic": per_topic,
                                                  "threshold": THRESHOLD}, indent=2), encoding="utf-8")
    md = to_markdown(pooled, per_topic, counts)
    (out / "balance.md").write_text(md, encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
