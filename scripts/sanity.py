"""Reproduce the KuaiRand paper's basic statistics for KuaiRand-1K.

Writes results/sanity.md and results/sanity.json. This only counts rows, users
and videos, and describes the random flag. It computes no outcome of the study.

    python scripts/sanity.py
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src import data  # noqa: E402

# Table 1 of Gao et al. (CIKM 2022, arXiv:2208.08696), KuaiRand-1K rows.
# The same numbers are in the README at https://github.com/chongminggao/KuaiRand.
PAPER = {
    "standard": {"users": 1000, "items": 4369953, "interactions": 11713045},
    "random": {"users": 1000, "items": 7388, "interactions": 43028},
}
POOL_SIZE = 7583          # videos in the random pool (full dataset)
MIN_RANDOM_PER_USER = 10  # the paper drops users with fewer random videos than this


def compare(ours: dict, paper: dict) -> list[dict]:
    """One row per statistic: paper value, our value, and whether they match."""
    rows = []
    for policy in ("standard", "random"):
        for stat in ("users", "items", "interactions"):
            p, o = paper[policy][stat], ours[policy][stat]
            rows.append({"policy": policy, "statistic": stat, "paper": p, "ours": o,
                         "difference": o - p, "match": o == p})
    return rows


def describe(random, standard) -> dict:
    """Checks on the random flag, the dates and the per-user counts."""
    per_user = data.per_user_counts(random)
    return {
        "random_log_is_rand_share": float(random["is_rand"].mean()),
        "standard_log_is_rand_share": float(standard["is_rand"].mean()),
        "random_first_date": int(random["date"].min()),
        "random_last_date": int(random["date"].max()),
        "standard_first_date": int(standard["date"].min()),
        "standard_last_date": int(standard["date"].max()),
        "random_per_user_min": int(per_user.min()),
        "random_per_user_median": float(per_user.median()),
        "random_per_user_max": int(per_user.max()),
        "standard_per_user_median": float(data.per_user_counts(standard).median()),
        # Random rows as a share of everything shown in the random period.
        "random_share_of_period": float(
            len(random) / (len(random) + int((standard["date"] >= random["date"].min()).sum()))),
    }


def to_markdown(rows: list[dict], extra: dict) -> str:
    lines = [
        "# Sanity check against the KuaiRand paper",
        "",
        "Generated by `scripts/sanity.py`. Paper values are from Table 1 of Gao et al.",
        "(CIKM 2022), KuaiRand-1K rows. \"Standard\" is the ordinary feed (the paper's",
        "\"15 policies\"), 8 April to 8 May 2022. \"Random\" is the randomly inserted videos.",
        "",
        "| Log | Statistic | Paper | This repo | Difference | Match |",
        "|---|---|---:|---:|---:|---|",
    ]
    for r in rows:
        lines.append(f"| {r['policy']} | {r['statistic']} | {r['paper']:,} | {r['ours']:,} | "
                     f"{r['difference']:+,} | {'yes' if r['match'] else 'NO'} |")
    lines += [
        "",
        "## Other checks",
        "",
        "| Check | Value | What the paper says |",
        "|---|---:|---|",
        f"| Share of random-log rows flagged random | {extra['random_log_is_rand_share']:.4f} | all of them |",
        f"| Share of standard-log rows flagged random | {extra['standard_log_is_rand_share']:.4f} | none of them |",
        f"| Random log dates | {extra['random_first_date']} to {extra['random_last_date']} | 22 April to 8 May 2022 |",
        f"| Standard log dates | {extra['standard_first_date']} to {extra['standard_last_date']} | 8 April to 8 May 2022 |",
        f"| Fewest random videos for any user | {extra['random_per_user_min']} | at least {MIN_RANDOM_PER_USER} |",
        f"| Median random videos per user | {extra['random_per_user_median']:.0f} | not stated |",
        f"| Most random videos for any user | {extra['random_per_user_max']} | not stated |",
        f"| Median ordinary impressions per user | {extra['standard_per_user_median']:.0f} | \"thousands\" on average |",
        f"| Random share of impressions, 22 April to 8 May | {100 * extra['random_share_of_period']:.2f}% | about 0.37% (full dataset) |",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--raw-dir", default="data/raw")
    p.add_argument("--out-dir", default="results")
    args = p.parse_args(argv)

    cols = ["user_id", "video_id", "date", "is_rand"]
    random = data.load_random(args.raw_dir, cols)
    standard = data.load_standard(args.raw_dir, cols)
    ours = {"standard": data.basic_stats(standard), "random": data.basic_stats(random)}
    rows = compare(ours, PAPER)
    extra = describe(random, standard)

    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "sanity.json").write_text(json.dumps({"table": rows, "checks": extra}, indent=2), encoding="utf-8")
    (out / "sanity.md").write_text(to_markdown(rows, extra), encoding="utf-8")
    print(to_markdown(rows, extra))
    return 0


if __name__ == "__main__":
    sys.exit(main())
