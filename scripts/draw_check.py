"""Was the random draw limited to videos the user had not been shown?

The balance table shows treated exposures start with a slightly lower share of the
topic. One explanation: the app never re-shows a video, so a fan of a topic, who has
already seen more of that topic's pool videos, is a little less likely to draw one.
This script checks the part of that story the logs can show. It was not in the
pre-registration (see DEVIATIONS.md). Writes results/draw_check.md and .json.

    python scripts/draw_check.py
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src import data  # noqa: E402


def repeat_stats(random: pd.DataFrame) -> dict:
    """How often a user got the same random video twice, against what uniform draws
    with replacement from the pool would give."""
    pool = random["video_id"].nunique()
    n = random.groupby("user_id").size()
    expected = float((n * (n - 1) / 2 / pool).sum())   # expected repeated draws, summed over users
    observed = int(random.duplicated(["user_id", "video_id"]).sum())
    return {"pool": int(pool), "exposures": int(len(random)), "repeats_observed": observed,
            "repeats_expected_with_replacement": expected}


def seen_before_stats(random: pd.DataFrame, standard: pd.DataFrame) -> dict:
    """How often the random video had already appeared in the user's ordinary feed,
    against the share of the pool the user had already been shown at that moment."""
    pool = pd.Index(random["video_id"].unique())
    seen = standard[standard["video_id"].isin(pool)].groupby(["user_id", "video_id"])["time_ms"].min()
    seen = seen.rename("first_seen").reset_index()
    m = random.merge(seen, on=["user_id", "video_id"], how="left")
    observed = int((m["first_seen"] < m["time_ms"]).sum())
    # expected: for each exposure, pool videos the user had already been shown / pool size
    seen = seen.sort_values("first_seen")
    expected = 0.0
    by_user = {u: g["first_seen"].to_numpy() for u, g in seen.groupby("user_id")}
    for u, g in random.groupby("user_id"):
        times = by_user.get(u)
        if times is not None:
            expected += float(pd.Series(times).searchsorted(g["time_ms"].to_numpy(), side="left").sum()) / len(pool)
    return {"already_in_feed_observed": observed, "already_in_feed_expected_if_ignored": expected}


def to_markdown(r: dict) -> str:
    return "\n".join([
        "# Did the random draw skip videos the user had already been shown?",
        "",
        "Generated by `scripts/draw_check.py`. Not pre-registered; see `DEVIATIONS.md`.",
        "",
        "| Check | Observed | Expected if the draw ignored history |",
        "|---|---:|---:|",
        f"| Same random video shown twice to one user | {r['repeats_observed']:,} | "
        f"{r['repeats_expected_with_replacement']:,.0f} |",
        f"| Random video already shown in the user's ordinary feed (8 April onwards) | "
        f"{r['already_in_feed_observed']:,} | {r['already_in_feed_expected_if_ignored']:,.0f} |",
        "",
        f"Out of {r['exposures']:,} random exposures drawn from a pool of {r['pool']:,} videos.",
        "Both counts are far below what a draw that ignored history would give. So the random",
        "video was drawn from videos the user had not been shown yet. The logs start on 8 April,",
        "so earlier viewing is invisible here and the true effect of this rule is larger.",
        "",
    ])


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--raw-dir", default="data/raw")
    p.add_argument("--out-dir", default="results")
    args = p.parse_args(argv)
    cols = ["user_id", "video_id", "time_ms"]
    random = data.load_random(args.raw_dir, cols)
    standard = data.load_standard(args.raw_dir, cols)
    r = {**repeat_stats(random), **seen_before_stats(random, standard)}
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "draw_check.json").write_text(json.dumps(r, indent=2), encoding="utf-8")
    (out / "draw_check.md").write_text(to_markdown(r), encoding="utf-8")
    print(to_markdown(r))
    return 0


if __name__ == "__main__":
    sys.exit(main())
